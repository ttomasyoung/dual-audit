#!/usr/bin/env node
// dual-audit:package-file (installed by dual-audit; ownership marker — do not remove)
// profile.js — parse, validate and compile a dual-audit profile.
//
// Two jobs:
//   check    <user.yaml> [base-dir]           validate syntax and schema, report problems
//   compile  <user.yaml> <panel.js> [base-dir] write the generated PROFILE block into the
//                                              installed panel
//   show     <user.yaml> [base-dir]           print the compiled profile as JSON
//
// WHY COMPILE INSTEAD OF READ AT RUN TIME: the panel runs inside a workflow sandbox with no
// filesystem access, so it cannot read a profile itself. The profile is therefore compiled into
// the installed panel between two markers, together with a hash of the source file, and
// `dual-audit doctor` reports when the source has changed since.
//
// The YAML SUBSET is deliberately small and every unsupported construct is a LOUD error rather
// than a quiet misreading. Supported: nested maps by two-space indentation, lists of scalars,
// lists of maps, single-line plain or quoted scalars, `[]` for an empty list, `#` comments.
// Not supported: tabs for indentation, block scalars (| >), anchors and aliases (& *), flow
// maps ({}), multiple documents, multi-line strings.

'use strict'
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const MARK_START = '// >>> DUAL-AUDIT PROFILE (generated by `dual-audit profile apply` — do not edit by hand) >>>'
const MARK_END = '// <<< END DUAL-AUDIT PROFILE <<<'

class ProfileError extends Error {}

// ---------------------------------------------------------------------------
// YAML subset parser
// ---------------------------------------------------------------------------

function stripComment(line) {
  // A '#' only starts a comment at the start of the line or after whitespace, and never inside
  // a quoted scalar. Getting this wrong would silently truncate a value containing '#'.
  let quote = null
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (quote) { if (c === quote) quote = null; continue }
    if (c === '"' || c === "'") { quote = c; continue }
    if (c === '#' && (i === 0 || /\s/.test(line[i - 1]))) return line.slice(0, i)
  }
  return line
}

function parseScalar(raw, where) {
  const s = raw.trim()
  if (s === '') return ''
  // Flow sequence: [a, b, "c d"]. Common enough in hand-written YAML that not supporting it
  // would mean silently reading a list as a string, which is exactly the class of quiet
  // misreading this parser exists to avoid.
  if (s[0] === '[') {
    if (s[s.length - 1] !== ']') throw new ProfileError(`${where}: unterminated flow list — keep it on one line`)
    const body = s.slice(1, -1).trim()
    if (body === '') return []
    const items = []
    let cur = '', quote = null
    for (let i = 0; i < body.length; i++) {
      const c = body[i]
      if (quote) { cur += c; if (c === quote) quote = null; continue }
      if (c === '"' || c === "'") { quote = c; cur += c; continue }
      if (c === ',') { items.push(cur); cur = ''; continue }
      if (c === '[' || c === '{') throw new ProfileError(`${where}: nested flow collections are not supported`)
      cur += c
    }
    if (quote) throw new ProfileError(`${where}: unterminated quoted string inside a flow list`)
    items.push(cur)
    // An empty item — `[a, , b]`, or the trailing comma in `[a, b, ]` — used to be dropped silently.
    // Quietly returning a list of a different length than the one written is the exact behaviour this
    // parser exists to avoid, so it is refused instead. Say what to change rather than guessing.
    for (const raw of items) {
      if (raw.trim() === '') throw new ProfileError(`${where}: empty item in a flow list — remove the stray comma rather than leaving a gap`)
    }
    return items.map(x => parseScalar(x, where))
  }
  if (s === 'true') return true
  if (s === 'false') return false
  if (s === 'null' || s === '~') return null
  // A value that OPENS with a quote must CLOSE with the same quote. Falling through to the
  // plain-scalar branch instead would silently turn `docs: "missing the closing quote` into the
  // string `"missing the closing quote` — a value that looks non-empty to every downstream check
  // while pointing at nothing. Downstream that is a real fail-open: a project whose `docs` is
  // non-empty satisfies the high-risk anchor requirement, so an audit could converge while the
  // independent reviewer had nothing readable to read.
  if (s[0] === '"' || s[0] === "'") {
    // The closing quote must be a REAL terminator. `"/some/path\"` ends with a quote character,
    // but that quote is escaped, so the string is still unterminated — accepting it would hand
    // back a truncated path that looks perfectly valid to every downstream check.
    const escaped = (() => {
      let n = 0
      for (let i = s.length - 2; i >= 0 && s[i] === '\\'; i--) n++
      return n % 2 === 1
    })()
    if (s.length < 2 || s[s.length - 1] !== s[0] || escaped) {
      throw new ProfileError(`${where}: unterminated quoted string — a value that opens with ${s[0]} must close with an unescaped ${s[0]}`)
    }
    const body = s.slice(1, -1)
    return s[0] === '"' ? body.replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\') : body
  }
  if (/^-?\d+$/.test(s)) return parseInt(s, 10)
  for (const bad of ['|', '>', '&', '*', '{', '`']) {
    if (s[0] === bad) {
      throw new ProfileError(`${where}: unsupported YAML syntax starting with '${bad}'. ` +
        `This parser accepts single-line scalars only — quote the value, or keep it on one line.`)
    }
  }
  return s
}

function parseYamlSubset(text, file) {
  const rawLines = text.split(/\r\n|\n/)
  const lines = []
  let sawDocStart = false
  rawLines.forEach((l, i) => {
    if (/^\t/.test(l) || /^ *\t/.test(l)) {
      throw new ProfileError(`${file}:${i + 1}: tab used for indentation. Use spaces.`)
    }
    const body = stripComment(l)
    if (body.trim() === '') return
    if (/^---\s*$/.test(body)) {
      // One document per file. A second `---` would otherwise merge two documents into one map,
      // so a profile could contain settings that appear to be overridden but are not.
      if (sawDocStart || lines.length) {
        throw new ProfileError(`${file}:${i + 1}: multiple YAML documents are not supported — keep one profile per file`)
      }
      sawDocStart = true
      return
    }
    lines.push({ n: i + 1, indent: body.match(/^ */)[0].length, text: body.trim() })
  })

  let pos = 0
  const peek = () => lines[pos]

  function parseBlock(indent) {
    const first = peek()
    if (!first) return null
    return first.text.startsWith('- ') || first.text === '-' ? parseList(indent) : parseMap(indent)
  }

  function parseMap(indent) {
    // Null prototype, deliberately. On an ordinary object literal, assigning the key `__proto__` sets
    // the prototype instead of creating a property: the line parses, the key vanishes from the result,
    // and no error is raised — a silent drop in a parser whose entire contract is that it never reads
    // one thing as another. With no prototype, `__proto__` is an ordinary key that then fails schema
    // validation out loud.
    const out = Object.create(null)
    while (pos < lines.length) {
      const l = peek()
      if (l.indent < indent) break
      if (l.indent > indent) throw new ProfileError(`${file}:${l.n}: unexpected indentation`)
      if (l.text.startsWith('- ')) break
      const m = /^([A-Za-z_][A-Za-z0-9_-]*)\s*:(.*)$/.exec(l.text)
      if (!m) throw new ProfileError(`${file}:${l.n}: expected "key: value", got ${JSON.stringify(l.text)}`)
      const key = m[1]
      const rest = m[2].trim()
      // The compiled profile is embedded in the panel as a JavaScript object LITERAL, and in a literal
      // `"__proto__":` sets the prototype rather than adding a property. Carrying such a key through
      // would mean the profile the panel ends up with is not the profile that was validated.
      if (key === '__proto__') {
        throw new ProfileError(`${file}:${l.n}: "__proto__" cannot be used as a key — it would change the shape of the compiled profile rather than adding a setting`)
      }
      if (Object.prototype.hasOwnProperty.call(out, key)) {
        throw new ProfileError(`${file}:${l.n}: duplicate key "${key}" — one of the two values would be silently discarded`)
      }
      pos++
      if (rest !== '') {
        out[key] = parseScalar(rest, `${file}:${l.n}`)
      } else {
        const next = peek()
        out[key] = (next && next.indent > indent) ? parseBlock(next.indent) : null
      }
    }
    return out
  }

  function parseList(indent) {
    const out = []
    while (pos < lines.length) {
      const l = peek()
      if (l.indent < indent) break
      if (l.indent > indent) throw new ProfileError(`${file}:${l.n}: unexpected indentation inside a list`)
      if (!l.text.startsWith('- ') && l.text !== '-') break
      const rest = l.text === '-' ? '' : l.text.slice(2).trim()
      if (/^([A-Za-z_][A-Za-z0-9_-]*)\s*:/.test(rest)) {
        // A list item that is a map: re-indent the inline part and keep reading siblings.
        const itemIndent = l.indent + 2
        lines[pos] = { n: l.n, indent: itemIndent, text: rest }
        out.push(parseMap(itemIndent))
      } else if (rest === '') {
        pos++
        const next = peek()
        out.push(next && next.indent > indent ? parseBlock(next.indent) : null)
      } else {
        pos++
        out.push(parseScalar(rest, `${file}:${l.n}`))
      }
    }
    return out
  }

  const doc = parseBlock(0)
  if (pos < lines.length) throw new ProfileError(`${file}:${lines[pos].n}: could not parse this line`)
  return doc === null ? {} : doc
}

