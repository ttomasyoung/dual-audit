// ---- STRICT sentinel parser: last block, by-line, exact first-token, fail-closed ----
// Split on EVERY Unicode line terminator. A bare split('\n') left a foreign AUDIT-ID separated by U+2028/
// U+2029 or a lone CR on the same logical line as far as the scanner was concerned, so it never entered the
// "all ids must match" comparison.
// What RENDERS as a line break must PARSE as a line break. VT/FF/FS/GS/RS/US display as line breaks
// in most terminals and editors but are not JavaScript line terminators, so `EVIDENCE: x<VT>P0: real
// blocker` looks like two lines to a human -- the second being a real P0 -- while the parser sees a
// single line, the P0 vanishes silently and the panel converges. If a human reads two lines, so must
// the parser; otherwise the two are looking at different verdicts.
const LINE_BREAKS = /\r\n|[\n\r\u2028\u2029\u0085\u000b\u000c\u001c\u001d\u001e\u001f]/
function splitLines(s) { return String(s == null ? '' : s).split(new RegExp(LINE_BREAKS.source, 'g')) }
// A6: `"\u200b".trim` is "\u200b", NOT "" \u2014 zero-width/format characters are
// not whitespace to String.trim. So `EVIDENCE: <U+200B>` passed a `.trim.length > 0` emptiness check and a
// verdict citing literally nothing converged (reproduced). Strip the invisible/format set BEFORE any emptiness
// test. NOTE: this is WIDER than the AUDIT-ID recognizer's own class (which still enumerates a narrow set);
// they are deliberately NOT the same today. An earlier comment here claimed they could not drift apart -- that
// was false. Widening the identity layer is a separate, higher-risk change and has not been made.
// Enumerating a hand-picked set was incomplete: U+2061..U+2064 (FUNCTION APPLICATION / INVISIBLE TIMES /
// INVISIBLE SEPARATOR / INVISIBLE PLUS) and U+180E all sailed through, so `EVIDENCE: <U+2063>` still counted as
// non-empty and converged. Use the Unicode FORMAT category itself \u2014
// it covers the whole class, including characters added later, instead of a list that has to be maintained.
// (Zs-style spaces are already handled by String.trim; Cf is exactly what trim does NOT remove.)
// `\p{Cf}` alone was still incomplete: U+034F COMBINING GRAPHEME JOINER and any bare combining mark are `Mn`,
// not `Cf`, so `EVIDENCE: <U+034F>` survived and converged.
// For an EMPTINESS test the right question is "is there any character that carries content on its own" —
// format chars, control chars and *bare* combining marks (no base character) all answer no.
// ORDER MATTERS: normalise with NFKC first, THEN strip. NFKC CREATES new combining marks (U+00B4
// becomes space + U+0301), so stripping first leaves the newly created marks in the string and
// `unchanged<mark>` slips past the vocabulary. The class includes Mc (spacing combining marks):
// a lone U+093E has no base character and carries no content.
const INVIS_RE = /[\p{Cf}\p{Cc}\p{Mn}\p{Me}\p{Mc}]/gu
// A BARE combining mark (nothing before it) carries no content; a mark ATTACHED to a letter is part
// of normal text. Deleting every Mn/Me/Mc unconditionally turns `no<U+0338>` (a struck-through "no")
// into `no` and misreads it as a non-answer. The emptiness test may strip all of them; semantic
// matching may strip only the bare ones.
const BARE_MARK_RE = /(^|[\s\p{Cf}\p{Cc}\p{P}\p{S}])[\p{Mn}\p{Me}\p{Mc}]+/gu
function stripBareMarks(s) { let p = null, cur = String(s); while (cur !== p) { p = cur; cur = cur.replace(BARE_MARK_RE, '$1') } return cur }
// Strip only; no NFKC here. Semantic normalisation is normVariants' job, and the emptiness test does
// not need NFKC (trim plus INVIS_RE is enough).
function normStrip(s) { return String(s == null ? '' : s).replace(INVIS_RE, '') }
function stripInvisible(s) { return normStrip(s) }
// DELETING invisible characters GLUES neighbouring words together: `same<U+200B>as<U+200B>the`
// becomes `sameasthe`, matches no vocabulary entry, and is waved through. Deletion is right for the
// emptiness test but creates a blind spot for semantic matching, so semantic matching always tries
// BOTH candidate forms -- deleted and replaced-with-space -- and a hit in either counts.
function normVariants(s) {
  const base = stripBareMarks(String(s == null ? '' : s).normalize('NFKC'))
  const fmt = /[\p{Cf}\p{Cc}]/gu
  return [base.replace(fmt, ''), base.replace(fmt, ' ')]
}
// ======== Non-answer detection: the HARD gate is structural only; prose judgement is advisory ========
// Deciding whether a piece of natural language says anything is not something lexical rules can do.
// Every vocabulary tightened against one batch of paraphrases was defeated by the next
// (`unchanged from R1`, `same as the previous round`, zero-width-glued words, `no difference from`,
// `as before`, `still unchanged`, `no modifications`, and the same phrases in other languages).
// Worse, tightening always misfires: adding `evidence`/`provided`/`citation` to catch "no evidence"
// rejects the legitimate `evidence provided above` and `same citation as above`. The same words form
// both a non-answer and a legitimate reference; they are lexically inseparable, and that is a property
// of the problem, not a vocabulary that is still too small.
// So the safety guarantee rests on something else: not "does this text say anything" (undecidable
// here) but "a flip must stay stable across rounds" (decidable -- see the freshFlip gate).
// This function keeps only the decidable part: is the field empty, and is the whole field exactly one
// placeholder token.
const NON_ANSWER_SENTINELS = new Set([
  'none', 'n a', 'na', 'nil', 'null', 'nan', 'nothing', 'tbd', 'unchanged', 'same', 'no change', 'no changes',
  '无', '無', '没有', '沒有', '无变化', '無變化', '沒有變化', '不变', '不變', '同上', '同前', '暂无', '暫無', '未提供',   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
  '変更なし', 'なし', '없음',   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
])
// STRUCTURAL non-answer = the field is empty, or its entire value is exactly one placeholder token.
// The crucial difference from the abandoned closed-vocabulary test: this matches the WHOLE field and
// never parses prose. It cannot be defeated by paraphrase -- it never claimed to handle prose -- and
// it cannot misfire on legitimate content, because a field that actually says something is never the
// literal string "none". Honest boundary: prose such as "no supporting evidence" is NOT caught here;
// the freshFlip stability gate backs that case and an advisory flags it for the reader.
// Emptiness must be judged BEFORE punctuation folding: folding first makes a legitimate symbolic
// DELTA such as `!=` look empty and rejects it.
function isStructuralNonAnswer(v) {
  if (!normStrip(v == null ? '' : v).trim()) return true   // emptiness uses the deleted form; a string of invisible characters is empty
 // BOTH forms must be tried. The sentinel set contains MULTI-WORD entries (`no change`,
 // `no changes`), so `no<U+200B>change` collapses to `nochange` under deletion (no match) and only
 // the replace-with-space form restores `no change` (match). Dropping either form leaks.
 // A mutation test reporting "no observable difference" for the second form only meant that no case
 // covered it -- mutation testing cannot find a gap nobody tested, and is not proof of redundancy.
  return normVariants(v).some(cand => {
    const k = cand.toLowerCase().replace(/[\s\p{P}\p{S}]+/gu, ' ').replace(/\s+/g, ' ').trim()
    return NON_ANSWER_SENTINELS.has(k)
  })
}
// Legacy name kept: the hard gate is now structural only, though call sites still say isTrivialDelta.
function isTrivialDelta(d) { return isStructuralNonAnswer(d) }
// ADVISORY only -- never part of the converged computation. The closed-vocabulary heuristic survives
// solely to flag suspicious fields to the reader. Its limits are explicit: incomplete by construction
// (paraphrase always escapes) and capable of false positives, so it can only ever be a warning.
// It no longer carries an EVIDENCE-specific vocabulary: that is what misjudged `evidence provided above`.
function looksLikeNonAnswerAdvisory(v) {
  if (normStrip(v == null ? '' : v).trim() === '') return false   // empty values are the structural gate's job; do not warn twice
  return normVariants(v).some(cand => matchesNonAnswer(cand))
}
// stripRefs: only DELTA needs referring expressions stripped (`same as the previous round`).
// EVIDENCE must NOT be stripped -- citing "r1 evidence" points at something real, and stripping `r1`
// leaves the bare word `evidence`, which then reads as no evidence at all.
function matchesNonAnswer(candidate, extraVocab, stripRefs) {
  const raw = candidate.trim()
  if (!raw) return true
  const n = raw.toLowerCase()
    .replace(/[\s\p{P}\p{S}]+/gu, ' ')
    .replace(/\s+/g, ' ').trim()
 // Judge only EMPTY values and EXPLICIT non-answers; never try to decide mechanically whether a
 // field "says something". Independent reviews converged on this: lexical heuristics cannot do it,
 // and every tightening produced a new class of false rejections -- a 12-character minimum rejected a
 // short but substantive non-Latin sentence while admitting the 15-character `changed changed`;
 // counting content units admitted `ok ok ok` while rejecting space-free Thai, Arabic and NFD Korean.
 // Honest boundary: this gate guarantees only that the field was actually filled in and is not a
 // plain "nothing changed". Whether a DELTA carries genuinely new evidence is for the reader to
 // judge; the panel cannot decide that and does not pretend to.
 // An English-only vocabulary treats the non-English equivalents of "no change" as substantive, which
 // is why the sentinel set is multilingual.
 // Method: first strip purely REFERRING tails (`from R1`, `as above`), then test what remains.
  const stripped = n
    .replace(/\b(from|vs|versus|than|as|to|with|since|compared|comparing|relative)\b/g, ' ')
    .replace(/\b(the|my|our|its|this|that)\b/g, ' ')   // not a/an: `n/a` normalises to `n a`, and stripping `a` would wash it down to `n`
    .replace(/\b(r1|r2|r3|round|rounds|above|prior|previous|last|earlier|before|stance|position|verdict)\b/g, ' ')
    .replace(/\b(see|seen)\b/g, ' ')
    .replace(/\b(has|have|had|is|are|was|were|been|any|at|all|in|of)\b/g, ' ')
    .replace(/(与|跟|和|同|比|对)?(上一轮|上轮|前一轮|上面|以上|之前|原来|先前|前次|上次)/g, ' ')   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
    .replace(/(相比|对比|比较|来说|而言|一致|任何|完全|丝毫)/g, ' ')   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
    .replace(/\s+/g, ' ').trim()
 // Honest boundary, unchanged: this catches EXPLICIT non-answers only. Verbose emptiness ("we
 // looked again and it seems fine") still passes -- whether the content is genuinely new evidence is
 // something only the reader can judge.
 // Match BOTH the normalised original and the remainder after referring expressions are stripped; a
 // hit in either counts. Matching only the remainder misses `n/a`; matching only the original misses
 // `same as the previous round`.
 // No phrase list. Phrase lists were defeated repeatedly on this axis. The test is structural
 // instead: negation words, change words, state words and function words each form a small CLOSED
 // set, and if every remaining token falls inside those sets, the sentence says nothing. That is a
 // bounded rule -- a new phrase built from those words matches automatically, with nothing to chase.
  // A bare `n` is included: normalisation turns `n/a` into `n a`.
  const NEG = 'no|not|none|nil|nothing|never|without|n|na|无|没|没有|未|不'   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
  const CHG = 'change|changed|changes|changing|difference|differences|diff|new|update|updated|movement|move|moved|变化|变动|变更|区别|差异|改变|变|新'   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
  const STA = 'same|identical|unchanged|still|as|before|above|previous|prior|last|earlier|already|相同|一样|同上|同前|不变|依旧|仍|仍然|照旧'   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
  const FILL = 'is|are|was|were|be|been|being|has|have|had|do|does|did|any|all|at|in|on|of|from|to|the|a|an|my|our|its|it|this|that|there|and|or|but|so|yet|here'
  const CLOSED = new RegExp('^(' + [NEG, CHG, STA, FILL].concat(extraVocab ? [extraVocab] : []).join('|') + ')$')
 // CJK has no inter-word spaces, so check character by character against the single-character set.
  const CJK_BASE = '无没有未不变化动更区别差异改相同一样上前依旧仍然照新'   // sanitize-scan:allow (multilingual non-answer vocabulary; functional data, not prose)
  const CJK_EXTRA = (extraVocab || '').replace(/[^\u4e00-\u9fff]/gu, '')
  const CJK_CLOSED = new RegExp('^[' + CJK_BASE + CJK_EXTRA + ']+$', 'u')
 // Stripping inserts spaces, which breaks CJK matching, so also try a form with all spaces removed.
  const squeezed = stripped.replace(/\s+/gu, '')
  const allClosed = (str) => {
    const t = str.split(/\s+/).filter(Boolean)
 // An empty token set is NOT a hit: emptiness is decided earlier, on the raw value. Returning true
 // here would misread a symbolic DELTA such as `!=` (empty after folding) as a non-answer.
    if (!t.length) return false
    return t.every(x => CLOSED.test(x) || CJK_CLOSED.test(x))
  }
  if (stripRefs === false) return allClosed(n)
  return allClosed(n) || allClosed(stripped) || allClosed(squeezed)
}
